def _blank(colour: tuple[int, int, int]) -> Any:
    from PIL import Image

    return Image.new("RGB", (1920, 917), colour)


def screen_without_overlay() -> Any:
    """一屏什么浮层都没有的画面（面板底色，那一块没有任何白）。"""
    return _blank((20, 30, 50))


def screen_all_white() -> Any:
    """整屏泛白——浏览器还在加载那一帧（`var/logs/rankv/00-baseline.png`）。

    ⚠️ 这一张专治「只看点阵重合」的判据：框里全白时 IoU 恰好是 167/306 = 0.546，
    离阈值只差一点点。挡住它的是静默环。
    """
    return _blank((255, 255, 255))


def screen_with(patch: tuple[str, ...]) -> Any:
    """把一块量下来的点阵贴回 `PATCH_ORIGIN`，其余留面板底色。"""
    image = screen_without_overlay()
    left, top = PATCH_ORIGIN
    for row, line in enumerate(patch):
        for column, mark in enumerate(line):
            if mark == "#":
                image.putpixel((left + column, top + row), (255, 255, 255))
    return image


