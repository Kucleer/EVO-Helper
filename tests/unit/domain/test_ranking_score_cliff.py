"""军力读数的**断崖判据**（`trusted_scores`）：跨屏锚点挡住的那两种 10 倍读错。

数全部来自 **2026-08-23 生产那一趟**（20:35）：两种 10 倍的军力读错都落了库，
而当时的两道网（按屏跑的 `descending_breaks` + `renderable_score`）一个都没挡住。

    93,670                  落在它那一屏的**第一行**（真值约 9,670，小数点被读成数字）
                            → 按屏跑的降序判据在屏首那一行没有前一个可比
    1,750 / 1,412 / 1,112   **整三屏**偏小 10 倍（真值约 11,750 / 11,412 / 11,112）
                            → 屏内 1,750 → 1,600 自成完好的降序，降序判据一个没抓到
                            （上一屏末尾 13,200、下一屏开头 10,980，断层只在跨屏处看得见）

两者都是 10 的整数倍，所以 `renderable_score` 也放过了。

所以下面每条用例的题眼都是 `anchor`：它是**上一屏最后一个可信值**，也是这道判据
唯一新增的东西。判据本身只答「信不信」，不猜真值——补值是 `interpolate_scores`
的事，标记是调用方的事。
"""

from __future__ import annotations

from evo_helper.domain.ranking import trusted_scores

# -- 生产那两个漏网，逐个钉住 ---------------------------------------------------


def test_a_tenfold_reading_on_the_first_row_is_caught_by_the_anchor() -> None:
    """⚠️⚠️ **生产漏网①：93,670 落在屏首，屏内没有前一个可比。**

    2026-08-23 生产实测：真值约 9,670，小数点被读成了一个数字（语料里见过
    `9.87K` → `93.87K` 同一形态）。它是那一屏的**第一行**，而
    `descending_breaks` 是按屏跑的——屏首那一行原先没有任何约束，于是直接落库。
    93,670 还是 10 的整数倍，`renderable_score` 也放它过去了。

    上一屏末尾是 9,650，把它带进来这一行立刻就是「比上一行大」。

    ⚠️ **只丢第一个。** 后面三行是好读数，一个都不许连坐——误伤的代价是把实读
    的军力值换成插值出来的估算值。
    """
    assert trusted_scores([93_670, 9_650, 9_650, 6_625], anchor=9_650) == [
        None,
        9_650,
        9_650,
        6_625,
    ]


def test_a_whole_screen_read_tenfold_small_is_refused_row_by_row() -> None:
    """⚠️⚠️ **生产漏网②：整三屏偏小 10 倍，而屏内自成完好的降序。**

    2026-08-23 生产实测把 `11.75K` / `11.41K` / `11.11K` 读成 `1.75K` / `1.41K` /
    `1.11K`——**丢了首位**。屏内 1,750 → 1,700 → 1,600 严格递减，降序判据一个都
    抓不到；三个数都是 10 的整数倍，`renderable_score` 也抓不到。

    断层只在**跨屏**处看得见：上一屏末尾 13,200，这一屏开头 1,750。所以拿锚点
    按倍数比是唯一认得出它的判据。

    ⚠️ **整屏都得丢，不是只丢第一行。** 被丢掉的第一行不许当后面那些的基准
    （见 `test_a_refused_reading_never_becomes_the_basis`），否则 1,700 相对
    1,750 完全正常，一次读错只丢一行、剩下两行照样进库。
    """
    assert trusted_scores([1_750, 1_700, 1_600], anchor=13_200) == [None, None, None]


def test_the_screen_after_a_refused_one_is_not_punished_for_it() -> None:
    """⚠️ **不许连坐。** 这就是生产那三屏之后紧接着的一屏（开头 10,980）。

    锚点仍是 13,200——上一屏整屏被判为不可信，锚点**沿用**旧值而不是跟着那批
    坏读数走（沿用那条在 `tools.ranking_scan.next_score_anchor` 上有自己的用例）。
    13,200 → 10,980 只跌了 17%，是榜单上正常的相邻名次差（语料实测跨 12 行
    只差 1.3%），一个都不许丢。

    这条守的是这道判据最容易被改坏的方向：把 `cliff_factor` 往 2 附近调、或者
    拿绝对差值代替倍数，都会先在这一屏上误伤。
    """
    assert trusted_scores([10_980, 10_900, 10_810], anchor=13_200) == [10_980, 10_900, 10_810]


def test_an_ordinary_screen_keeps_every_reading() -> None:
    """再往下一屏（锚点 10,980），全留。

    ⚠️ 采集段绝大多数屏长这样，所以这条是**基线**：它一红就说明这道判据在
    正常数据上就已经开始丢分数了，而丢掉的每一个都会变成插值出来的估算值。
    """
    assert trusted_scores([10_740, 10_700, 10_670], anchor=10_980) == [10_740, 10_700, 10_670]


def test_tied_scores_are_not_mistaken_for_a_broken_order() -> None:
    """⚠️ **并列同分不许误伤：判据是「严格大于」，不是「大于等于」。**

    榜上并列同分是常态（生产那一屏就有两行 9,650，见漏网①那条用例），而它同时
    **等于**锚点。写成 `>=` 的话，每一段同分都会被整段丢掉——那是把最常见的
    形状当成错读，误伤面比它要挡的故障大得多。
    """
    assert trusted_scores([10_740, 10_740, 10_700], anchor=10_740) == [10_740, 10_740, 10_700]


# -- 整趟第一屏：没有锚点时拿什么起头 -------------------------------------------


def test_the_first_screen_starts_from_the_median_not_from_the_first_reading() -> None:
    """⚠️⚠️ **没有锚点时用这一屏的中位数起头，中位数就是为这一屏加的。**

    整趟的第一屏没有上一屏可依。拿**第一个读数**当基准的话，93,670 自己成了基准，
    9,650 和 9,640 都变成「跌了 10 倍」——一个坏读数把整屏拖下水，**比不加这道
    判据还差**（不加的话至少那两个好读数能进库）。

    中位数抗单点异常：一个坏值动不了它，而它只用来起头，第一个可信值一出现基准
    就交给它。
    """
    assert trusted_scores([93_670, 9_650, 9_640]) == [None, 9_650, 9_640]


def test_the_median_is_never_used_as_the_previous_row() -> None:
    """⚠️⚠️ **中位数只当断崖基准，不许当降序基准。**

    一屏里最大的那个读数**天然高于中位数**——把中位数当成「前一行」，屏首那个
    正常的最大值就成了「比上一行大」，每一屏的第一行都会被丢掉一次。

    没有锚点时第一行的顺序本来就无从约束（这正是漏网①存在的原因），答案是
    「不知道」而不是「编一个前一行出来」。
    """
    assert trusted_scores([10_740, 10_700, 10_670]) == [10_740, 10_700, 10_670]


# -- 边界：读不出、屏内爬升、以及基准跟着谁走 -----------------------------------


def test_an_unreadable_reading_stays_unreadable_and_infects_nobody() -> None:
    """`None`（军力读不出）照旧是 `None`，前后两行都留。

    军力值本来就允许读不出（用户口径 2026-08-14），所以 `None` 不是异常信号，
    不许被当成「一次读错」而牵连邻居。
    """
    assert trusted_scores([10_700, None, 10_650], anchor=10_740) == [10_700, None, 10_650]


def test_a_reading_that_climbs_inside_the_screen_is_the_only_one_dropped() -> None:
    """屏内破坏降序的那一个，只丢它自己。

    这是原先 `descending_breaks` 唯一抓得住的形状，换判据之后**不许退化**：
    10,720 比它上一行 10,700 大，丢；而它后面的 10,650 相对**前一个可信值**
    （10,700）完全正常，留。
    """
    assert trusted_scores([10_700, 10_720, 10_650], anchor=10_740) == [10_700, None, 10_650]


def test_a_refused_reading_never_becomes_the_basis() -> None:
    """⚠️⚠️ **基准只跟着可信值走：一次读错不许把它后面整段拖下水。**

    93,670（漏网①那个数）被锚点判掉。要是它照样当上了下一行的基准，那么
    10,700 和 10,650 相对它就都是「跌了将近 10 倍」，**整屏一个都不剩**——
    一次读错的代价从「丢一个分数」放大成「丢一屏分数」。

    降序基准（`last`）和断崖基准（`basis`）两个都得守这条，所以这一屏两个方向
    的误判都会让它变红。
    """
    assert trusted_scores([93_670, 10_700, 10_650], anchor=10_740) == [None, 10_700, 10_650]


def test_the_cliff_basis_moves_forward_with_each_trusted_reading() -> None:
    """⚠️ **基准要往前走，不能一屏认死起点那一个。**

    这一屏是真实的陡降（榜单交界处会有，见 `SCORE_CLIFF_FACTOR` 上那条），
    每一步相对**前一行**都在 5 倍以内：100,000 → 90,000 → 30,000 → 19,000。

    基准要是一直停在起点 100,000 上，19,000 就成了「跌掉 5 倍以上」而被丢掉——
    一段合法的下坡会被自己的起点判死，而且越往后越容易被判死。
    """
    assert trusted_scores([90_000, 30_000, 19_000], anchor=100_000) == [90_000, 30_000, 19_000]
