"""哪个目标离出发星球更近。**只排序，不估时间。**

## 判据：先比银河，再比恒星系

用户口径（2026-08-14）：「银河系（第一个坐标）数值越接近出发星球的，距离越近。
同一个银河系，恒星系（第二个坐标）更接近的距离更近。」

也就是字典序 `(Δ银河, |Δ恒星系|)`——但**第一段不是减法**，见下。

## ⚠️ 银河是一个**环**：`abs(9 - 2)` 是 7，真实距离是 2

用户 2026-08-14 实测（同一套编组，速度 14.520、100%，从 **2** 系出发）：

    目标银河   飞行时间        秒     气体        线性差   环形差
       3      1时2分32秒     3752      —           1        1
       9      1时28分25秒    5305   446.84K        7        2
       8      1时48分17秒    6497   658.36K        6        3
       6      2时5分2秒      7502   869.88K        4        4
       7      2时5分2秒      7502   869.88K        5        4

银河共 9 个（`scan_bounds.TOTAL_GALAXIES`），首尾相接。所以从 2 系去 9 系
走的是 `2→1→9`，**两步**，不是七步。

### 最后两行是**判别性**证据，不只是又一个拟合点

`2→6` 正着走 4 步，`2→7` 倒着走 4 步——**环形差都是 4**，而线性差是 4 和 5。

    线性说：两者应当不同
    环形说：两者应当一模一样
    实测：  飞行时间和气体消耗都**一模一样**（用户反复核对了三遍）

两个模型在这里给出相反的预言，实测选了环形。这比任何拟合优度都硬。

### 拟合出来的式子是**精确**的

    飞行秒数 = 2 + 3750 × √环形银河距离      （速度 14.520 / 100%）

    环形 1 → 3752.0    实测 3752
    环形 2 → 5305.3    实测 5305
    环形 3 → 6497.2    实测 6497
    环形 4 → 7502.0    实测 7502

四个点全中。**换成线性差就彻底崩掉**：9 系会被算成 9924 秒（实测 5305），
差 4619 秒；8 系算成 9188 秒（实测 6497），差 2691 秒。

气体则是**线性**的（不是 √），而且精确到分：

    气体 = 211.52K × 环形银河距离 + 23.80K

    环形 2 → 446.84K   环形 3 → 658.36K   环形 4 → 869.88K   三个全中

⚠️ 所以 `distance_key` 第一段必须走 `galaxy_gap()`，**不许写 `abs(a - b)`**。
写成减法的话，从 2 系看，9 系会排在 5 系后面——而 9 系其实是**第二近**的银河。
这不会报错，只会让一夜的航线全排错。

## 跨银河之后，恒星系号对飞行时间**没有可测的影响**

用户 2026-08-14 的观察：「跨银河系之后，恒星系[相比]左边[的银河系]对时间的影响，
仅在秒级」。上面那张表把这条量化了：三个目标的恒星系号各不相同，
而一个**只含环形银河距离**的函数把它们全部命中在 2 秒内——恒星系号那一位
在跨银河时压根没进算式。

**对选目标的意思**：跨银河时「挑个恒星系更近的」是没有意义的。所以跨银河的目标
该按**别的**标准挑（军力值、资源量）。`distance_key` 第二段仍然保留 `|Δ恒星系|`，
因为它对**同银河**目标是真的（`within` 只放同银河的过），对跨银河目标则退化成
一个确定性的并列打破——无害，但**别把它当成距离**。

## ⚠️ 恒星系（1–499）是不是也成环？**不知道，所以按不成环处理**

银河成环，恒星系八成也成环——但**没有量过**，而这个方向的赌注是不对称的：

- 猜它成环、其实不成 → 把 2:499（从 2:137 看真实距离 362）当成 137，
  **以为很近其实很远**，舰队一去不回。
- 猜它不成环、其实成环 → 把真实的近目标排到后面，少打几发。

所以 `distance_key` / `within` 的恒星系那一段**故意用直的减法**。
要推翻很便宜：从 2:137 出发，量 `2:499` 和 `2:275`（若成环则两者近似等距）。
量到了再改，别凭「银河成环所以恒星系也成环」就动手。

## 同银河那一段是另一条曲线

`2:499:18`（同银河、系差 362）实测 1969 秒。上面那条跨银河曲线在环形差 0 处给出
0 秒，所以同银河显然是另一个式子（有基础耗时 + 恒星系项）。只有一个点，拟合不了，
留着备查。跨一个银河（3752 秒）仍然比同银河内最远的那一头（1969 秒）贵近一倍。

气体明显**不**跟着飞行时间走（446.84K → 658.36K，比值 1.47，而飞行时间比值只有
1.22）。两个点拟合大致是 `211K × 环形银河距离 + 24K`，但两个点说明不了什么。

## 为什么绝不把距离存成列

距离是 **(目标, 出发星球)** 的函数，不是目标自己的属性。

用户 2026-08-14 明确要求兼容「以后可能会多星球发出攻击，并且会配置航线」。存成列的
那一天，第二颗出发星球上的任务会拿着按主星算的距离排序——**而且完全不报错**，
只是打的顺序莫名其妙。仓里已有的 `count_inflight(origin=...)`、`fleet_lines`
都是按 origin 分账的，这条跟它们同一个形状。

## 位次只用来定序，不代表距离

同一个恒星系里的两颗星球，飞行时间差别可以忽略。把 `position` 放进排序键**只是
为了让结果确定**：不放的话，同距离目标的先后取决于库里的返回顺序，而那个顺序
在换一次查询、换一次索引之后就会变，事后对不上账。

## 这里**不**算飞行时间

拟合飞行时间曲线是另一件事（用户 2026-08-14 定为长期低优先级）。那需要按编组
速度分组、需要跨银河样本，而且形状八成是 `a + b·√距离`（三个同银河点拟合下来
误差 <1%）。在那之前，**排序不需要知道要飞多久，只需要知道谁更近**——
这两件事分开，排序就不会被一条还没验过的曲线拖住。
"""

from __future__ import annotations

from collections.abc import Iterable, Sequence

from evo_helper.domain.models import Coordinate
from evo_helper.domain.scan_bounds import TOTAL_GALAXIES


def galaxy_gap(target: int, origin: int, *, total: int = TOTAL_GALAXIES) -> int:
    """两个银河之间的**环形**距离：绕哪边近就算哪边。

    银河首尾相接（实测见模块头）。从 2 系去 9 系走 `2→1→9` 是两步，
    而 `abs(9 - 2)` 会算成七步——那个数在实机上对应 9922 秒，实测只有 5305 秒。

    最大值是 `total // 2`（9 个银河时是 4）：绕过半圈就该往回走了。
    """
    straight = abs(target - origin)
    return min(straight, total - straight)


def distance_key(target: Coordinate, origin: Coordinate) -> tuple[int, int, int]:
    """按「离 `origin` 由近到远」排序时用的键。小的在前。

    三段的地位完全不同，别把它们看成同一个量：

    1. **环形**银河距离 —— 压倒性的，而且**不是减法**（见 `galaxy_gap`）。
    2. `|Δ恒星系|` —— 同银河内的真实远近。跨银河时不影响时间，只是并列打破。
       **这一段是直的减法**：恒星系成不成环没量过，见模块头那条不对称赌注。
    3. `position` —— **只为定序**，不代表距离（同系内的差别可忽略）。
    """
    return (
        galaxy_gap(target.galaxy, origin.galaxy),
        abs(target.system - origin.system),
        target.position,
    )


def nearest_first(targets: Iterable[Coordinate], origin: Coordinate) -> tuple[Coordinate, ...]:
    """把目标按「离 `origin` 近的排前面」重排。

    ⚠️ **每个任务用它自己的 `origin` 现算**，不许缓存、不许存列——理由见模块头。

    用途（用户 2026-08-14）：一夜的航线是有限的，而近目标的往返时间比远目标短
    一个量级（同银河近距离约 20–30 分钟，跨银河约 2.6 小时）。同样 6 条航线，
    先打近的能派十几发，先打远的只能派两三发。

    排序是**稳定**的：`sorted` 保证同键的原有先后不变，而第三段 `position` 又
    把同一恒星系内的目标定死了顺序。两条加起来，同一批目标每次都排成同一个样子
    ——事后拿日志对账时这一点很要紧。
    """
    return tuple(sorted(targets, key=lambda target: distance_key(target, origin)))


def within(
    targets: Sequence[Coordinate], origin: Coordinate, *, systems: int
) -> tuple[Coordinate, ...]:
    """只留下**同银河**且恒星系差不超过 `systems` 的那些，仍按由近到远排。

    跨银河的一律不要：不是「远一点」，是贵一个量级（见模块头那两个实测数）。
    要打跨银河的目标时，把它做成另一个任务、配它自己的出发星球，而不是把半径调大。
    """
    near = [
        target
        for target in targets
        if target.galaxy == origin.galaxy and abs(target.system - origin.system) <= systems
    ]
    return nearest_first(near, origin)


__all__ = ["distance_key", "galaxy_gap", "nearest_first", "within"]
