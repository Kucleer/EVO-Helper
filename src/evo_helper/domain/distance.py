"""哪个目标离出发星球更近。**只排序，不估时间。**

## 判据：先比银河，再比恒星系

用户口径（2026-08-14）：「银河系（第一个坐标）数值越接近出发星球的，距离越近。
同一个银河系，恒星系（第二个坐标）更接近的距离更近。」

也就是字典序 `(Δ银河, Δ恒星系)`——但**两段都不是减法**：两个坐标各自成环，见下。

## ⚠️ 银河是一个**环**：`abs(9 - 2)` 是 7，真实距离是 2

用户 2026-08-14 实测（同一套编组，速度 14.520、100%，从 **2** 系出发）：

    目标银河   飞行时间        秒     气体        线性差   环形差
       3      1时2分32秒     3752      —           1        1
       9      1时28分25秒    5305   446.84K        7        2
       8      1时48分17秒    6497   658.36K        6        3
       6      2时5分2秒      7502   869.88K        4        4
       7      2时5分2秒      7502   869.88K        5        4

银河共 9 个（`scan_bounds.TOTAL_GALAXIES`），首尾相接。所以从 2 系去 9 系
走的是 `2→1→9`，**两步**，不是七步。

### 最后两行是**判别性**证据，不只是又一个拟合点

`2→6` 正着走 4 步，`2→7` 倒着走 4 步——**环形差都是 4**，而线性差是 4 和 5。

    线性说：两者应当不同
    环形说：两者应当一模一样
    实测：  飞行时间和气体消耗都**一模一样**（用户反复核对了三遍）

两个模型在这里给出相反的预言，实测选了环形。这比任何拟合优度都硬。

### 拟合出来的式子是**精确**的

    飞行秒数 = 2 + 3750 × √环形银河距离      （速度 14.520 / 100%）

    环形 1 → 3752.0    实测 3752
    环形 2 → 5305.3    实测 5305
    环形 3 → 6497.2    实测 6497
    环形 4 → 7502.0    实测 7502

四个点全中。**换成线性差就彻底崩掉**：9 系会被算成 9924 秒（实测 5305），
差 4619 秒；8 系算成 9188 秒（实测 6497），差 2691 秒。

气体则是**线性**的（不是 √），而且精确到分：

    气体 = 211.52K × 环形银河距离 + 23.80K

    环形 2 → 446.84K   环形 3 → 658.36K   环形 4 → 869.88K   三个全中

⚠️ 所以 `distance_key` 第一段必须走 `galaxy_gap()`，**不许写 `abs(a - b)`**。
写成减法的话，从 2 系看，9 系会排在 5 系后面——而 9 系其实是**第二近**的银河。
这不会报错，只会让一夜的航线全排错。

## 跨银河之后，恒星系号对飞行时间**没有可测的影响**

用户 2026-08-14 的观察：「跨银河系之后，恒星系[相比]左边[的银河系]对时间的影响，
仅在秒级」。上面那张表把这条量化了：三个目标的恒星系号各不相同，
而一个**只含环形银河距离**的函数把它们全部命中在 2 秒内——恒星系号那一位
在跨银河时压根没进算式。

**对选目标的意思**：跨银河时「挑个恒星系更近的」是没有意义的。所以跨银河的目标
该按**别的**标准挑（军力值、资源量）。`distance_key` 第二段仍然保留恒星系距离，
因为它对**同银河**目标是真的（`within` 只放同银河的过），对跨银河目标则退化成
一个确定性的并列打破——无害，但**别把它当成距离**。

## 恒星系（1–499）**也是环**，而且是量出来的

用户 2026-08-14 从 **2:137** 出发的三个同银河点：

    目标      飞行时间     秒     气体      线性差   环形差
    2:287    34分2秒     2042   86.37K     150      150
    2:499    32分49秒    1969   82.02K     362      137
    2:1      32分44秒    1964   81.68K     136      136

⚠️ **`2:499` 线性差 362，却比线性差只有 150 的 `2:287` 快 73 秒。**
任何单调的线性模型都给不出这个。而按环形排，时间顺序完全对上（150 > 137 > 136）。

还有一条更直白的：`2:499` 和 `2:1` 只差 **5 秒**——正好一个恒星系步长，
因为环上它们是相邻的（137 步和 136 步）。线性会说它们差 226 个恒星系。

恒星系共 499 个（`scan_bounds.SYSTEMS_PER_GALAXY`），499 与 1 相接。

## 完整模型（两条独立的量互相印证）

    环形距离    galaxy_gap / system_gap        （绕哪边近算哪边）
    距离单位 D  同银河：1162 + 31.71 × 恒星系环形距离
               跨银河：20000 × 银河环形距离
    飞行秒数    2 + 26.5165 × √D
    气体        0.010576 × D + 23.80  K

八个实测点全部命中（飞行时间 ±1 秒，气体 ±0.03K）。

**互相印证在哪里**：气体那两个常数是**只用跨银河数据**定出来的，而同银河的三个 D
是**只从飞行时间**反解的。拿前者去预测后者的气体，三个点全中在 0.03K 内。
两个互不相干的量落在同一把尺子上，这比单独拟合任何一条都硬。

顺带：跨一个银河（3752 秒）比同银河内最远的那一头（约 2042 秒）贵不到一倍——
比原先按线性算时估的「近一倍」要小，因为同银河的真实最远端只有 249 步而不是 498。

## 为什么绝不把距离存成列

距离是 **(目标, 出发星球)** 的函数，不是目标自己的属性。

用户 2026-08-14 明确要求兼容「以后可能会多星球发出攻击，并且会配置航线」。存成列的
那一天，第二颗出发星球上的任务会拿着按主星算的距离排序——**而且完全不报错**，
只是打的顺序莫名其妙。仓里已有的 `count_inflight(origin=...)`、`fleet_lines`
都是按 origin 分账的，这条跟它们同一个形状。

## 位次只用来定序，不代表距离

同一个恒星系里的两颗星球，飞行时间差别可以忽略。把 `position` 放进排序键**只是
为了让结果确定**：不放的话，同距离目标的先后取决于库里的返回顺序，而那个顺序
在换一次查询、换一次索引之后就会变，事后对不上账。

## 这里**不**算飞行时间

上面那个模型已经能把飞行时间算到 ±1 秒，但**这个模块不提供那个函数**。

理由是它只在**一套编组**（速度 14.520 / 100%）上验过。`26.5165` 那个系数里裹着
速度，换一套编组就是另一个数——而把一个只在一处成立的公式放出去，调用方不会知道
这件事。排序不需要它：`distance_key` 只用到「谁更近」，那是**纯序**的，
对任何速度都成立。

要做飞行时间估算（用户 2026-08-14 定为长期低优先级）就单开一个模块，
在那里显式收 `speed` 参数，并且用多套编组的实测把系数标出来。
"""

from __future__ import annotations

from collections.abc import Iterable, Sequence

from evo_helper.domain.models import Coordinate
from evo_helper.domain.scan_bounds import SYSTEMS_PER_GALAXY, TOTAL_GALAXIES


def ring_gap(target: int, origin: int, *, total: int) -> int:
    """首尾相接的一圈上，两点之间**绕哪边近就算哪边**。

    银河和恒星系都是环（实测见模块头），所以两边共用这一个函数。
    最大值是 `total // 2`：绕过半圈就该往回走了。
    """
    straight = abs(target - origin)
    return min(straight, total - straight)


def galaxy_gap(target: int, origin: int, *, total: int = TOTAL_GALAXIES) -> int:
    """两个银河之间的环形距离。

    从 2 系去 9 系走 `2→1→9` 是**两步**，而 `abs(9 - 2)` 会算成七步——
    那个数在实机上对应 9924 秒，实测只有 5305 秒。
    """
    return ring_gap(target, origin, total=total)


def system_gap(target: int, origin: int, *, total: int = SYSTEMS_PER_GALAXY) -> int:
    """同一银河内两个恒星系之间的环形距离。

    从 2:137 去 2:499 走的是 `137→…→1→499`，**137 步**，而 `abs(499 - 137)`
    会算成 362 步。实测 `2:499` 比线性差只有 150 的 `2:287` **还快 73 秒**——
    线性模型给不出这个（见模块头）。
    """
    return ring_gap(target, origin, total=total)


def distance_key(target: Coordinate, origin: Coordinate) -> tuple[int, int, int]:
    """按「离 `origin` 由近到远」排序时用的键。小的在前。

    三段的地位完全不同，别把它们看成同一个量：

    1. **环形**银河距离 —— 压倒性的，而且**不是减法**（见 `galaxy_gap`）。
    2. **环形**恒星系距离 —— 同银河内的真实远近，同样**不是减法**（见 `system_gap`）。
       跨银河时它不影响飞行时间，那时它只是个并列打破。
    3. `position` —— **只为定序**，不代表距离（同系内的差别可忽略）。

    ⚠️ 前两段都必须走 `*_gap()`。写成 `abs(a - b)` 不会报错，只会安静地把
    真正的近目标排到后面——实测 `2:499` 比 `2:287` 还快 73 秒，而线性差是 362 比 150。
    """
    return (
        galaxy_gap(target.galaxy, origin.galaxy),
        system_gap(target.system, origin.system),
        target.position,
    )


def nearest_first(targets: Iterable[Coordinate], origin: Coordinate) -> tuple[Coordinate, ...]:
    """把目标按「离 `origin` 近的排前面」重排。

    ⚠️ **每个任务用它自己的 `origin` 现算**，不许缓存、不许存列——理由见模块头。

    用途（用户 2026-08-14）：一夜的航线是有限的，而近目标的往返时间比远目标短
    一个量级（同银河近距离约 20–30 分钟，跨银河约 2.6 小时）。同样 6 条航线，
    先打近的能派十几发，先打远的只能派两三发。

    排序是**稳定**的：`sorted` 保证同键的原有先后不变，而第三段 `position` 又
    把同一恒星系内的目标定死了顺序。两条加起来，同一批目标每次都排成同一个样子
    ——事后拿日志对账时这一点很要紧。
    """
    return tuple(sorted(targets, key=lambda target: distance_key(target, origin)))


def within(
    targets: Sequence[Coordinate], origin: Coordinate, *, systems: int
) -> tuple[Coordinate, ...]:
    """只留下**同银河**且恒星系差不超过 `systems` 的那些，仍按由近到远排。

    跨银河的一律不要：不是「远一点」，是贵一个量级（见模块头那张表）。
    要打跨银河的目标时，把它做成另一个任务、配它自己的出发星球，而不是把半径调大。

    ⚠️ 半径按**环形**距离算。用减法的话，从 2:137 看 `2:499` 会被算成 362 而落在
    半径外——可它其实是第 137 近的，比一半的同银河目标都近。
    """
    near = [
        target
        for target in targets
        if target.galaxy == origin.galaxy and system_gap(target.system, origin.system) <= systems
    ]
    return nearest_first(near, origin)


