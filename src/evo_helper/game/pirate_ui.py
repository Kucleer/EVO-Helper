def snap_dialog(raw: str, *, max_distance: int = 3) -> str | None:
    """把弹窗正文贴回封闭词表；贴不上或有歧义就返回 None。

    **不能用子串判断**。实机（2026-08-10）把「派**遣**」读成了「派**遗**」——
    差一个字，`in` 直接漏掉；而漏掉的后果是弹窗认不出、runner 停下，
    但停的理由与真实原因无关，事后从现象根本猜不到是 OCR 少认了一个字。
    `snap_mission` 因为「攻击」被读成「政击」踩过同一个坑。

    `max_distance=3` 的依据（三屏实测）：正确候选的距离是 0 / 1 / 2，
    而最近的**错误**候选在 8——中间隔着 6，放到 3 既容得下再多一次抖动，
    也远不到会误判成另一个弹窗的地步。而误判是要命的：「跳过这个目标」
    和「停下整轮等航线」会做反。
    """
    return snap_to_vocabulary(raw, DIALOG_MESSAGES, max_distance=max_distance)


