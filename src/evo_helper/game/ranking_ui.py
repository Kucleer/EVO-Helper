#: 分步慢拖的起止点：面板横向中点，从 700 拖到 300。
#:
#: 按下点 (960, 700) 落在列表行上——列表行上没有控件，被当成点击也只是选中一行；
#: 但**仍然必须慢拖**，理由见 `ranking_nav.RankingNavigator._slow_drag`。
SCROLL_X = 960
SCROLL_FROM_Y = 700
SCROLL_TO_Y = 300

#: 拖完之后先等这么久再读。**只是个下限，不是「等够了」**——够不够由读出的
#: 行数说话（见 `SCROLL_SETTLE_MIN_ROWS`）。
#:
#: ⚠️ **原先是 2.0 秒，理由写的是「等惯性停下」——那个理由是错的。**
#: 2026-08-23 实机量过：分步慢拖在终点**静止 `DRAG_RELEASE_HOLD_S`(0.18) 秒才松手**，
#: 松手时速度已经是 0，**压根没有惯性滑动**。拿帧间竖向位移量 8 次拖动，
#: 停下用时 7 次是 0.00 秒、最慢 0.06 秒。
#:
#: ⚠️ **但不能因此就砍到 0。** 同一趟实机量了延迟曲线（10 次拖动 × 5 个时点，
#: 每格「读出行数 / 反解出 bot 坐标数」）：
#:
#:     等 0.00s   9/10 屏读满，**1 屏只读出 1 行**
#:     等 0.25s   同一屏 0 行
#:     等 0.50s   同一屏 1 行
#:     等 1.00s   同一屏 11 行 / 10 个 bot ✓
#:
#: 也就是**十屏里有一屏，内容要到 1 秒左右才就绪**（方案里的候选 C，懒加载）。
#: 固定值砍到 0.25 秒就是每 10 屏静默丢 1 整屏——和刚修掉的整屏漏采同一类。
#:
#: 所以改成「小下限 + 按行数补读」：常见情形省下 1.65 秒，没就绪的那一屏由
#: 补读兜住。取 0.35 是给「截图 + 起 OCR」留的一点余量，不是量出来的阈值。
SCROLL_SETTLE_WAIT_S = 0.35

#: 拖完读一屏，**行数少于这个数就再等 `REREAD_WAIT_S` 重读一次**。
#:
#: 一屏可见 11–14 行（`ROWS_PER_SCREEN` 13 是标定值，实测有浮动）。取 6（约半屏）
#: 是个宽松的下界：真实的满屏永远到不了这么低，而没就绪的那一屏实测是 0–1 行。
#:
#: ⚠️ **补读失败也不许丢数据。** 榜单最后一屏本来就可能不满 6 行，所以
#: `_rows_confirming` 在重试用尽之后交回**读到最多的那一次**，而不是空
