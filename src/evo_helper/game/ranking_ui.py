"""军力排行榜的界面坐标与几何。**每个数都是 2026-08-14 实机量的**（client 空间 1920×917）。

动作住在 `game.ranking_nav`，解析住在 `domain.ranking`；这里一个像素都不点。
改任何一个数之前先用 `tools/capture.py` 重拍一张核对，不要照抄文档。

## 进榜单的路径（实机走通）

    任意一屏
      → **横向拖**底部导航（`NAV_DRAG_FROM_X` → `NAV_DRAG_TO_X`）
      → 露出 `太空舱 商店 联盟 排名 设置`
      → OCR 标签行、按文本找「排名」、点它当屏读到的那个 x
      → 排行榜面板
      → 切「军事评分」→ **回读确认真的在军事榜上**

## ⚠️ 导航条是**拖**出来的，不是点箭头翻页的

`pirate_ui.NAV_SCROLL_RIGHT`（1204, 862）对这一段**无效**：实机上先点了它，
导航条纹丝不动。它不是这条路上的翻页箭头。这条写在这里是因为下一个人看到
「导航条要往右翻」第一反应一定是去点那个坐标，然后浪费一轮才发现它不动。

## ⚠️ 拖完之后，`pirate_ui` 的底部导航坐标**全部失效**

导航条是一条可横向滚动的条。拖之前 `NAV_PLANET`(840, 862) 是「行星」；
拖之后同一个像素上坐着的是**「太空舱」**（拖完它的中心在 x=830，差 10px）——
而 `pirate_ui` 里白纸黑字写着那个东西点开是材料仓库、会把整条导航条盖住。

所以拖过之后必须还原（`ranking_nav.RankingNavigator.close`），
而不是把条留在右段就把控制权交回去。同一条规矩在 `preset_picker.pick` 的
收尾里已经写过一遍：**下游坐标都是在条停在标定位置时量的**。
"""

from __future__ import annotations

# -- 底部导航：横向拖出「排名」 ------------------------------------------------

#: 导航条图标那一行的 y。**点击落在这一行**，OCR 读的是它下面的标签行。
NAV_BAR_Y = 862

#: 往左拖（内容左移、露出右段）的起止 x。实测拖完就出 `太空舱 商店 联盟 排名 设置`。
NAV_DRAG_FROM_X = 1122
NAV_DRAG_TO_X = 860

#: 拖完等惯性停下。
NAV_DRAG_WAIT_S = 1.2

#: 拖动次数上限。实测**一次**就够；留 2 次是给「打开时条停在更左边」留的余量，
#: 而不是给「拖不动就多拖几下」留的——拖不动时多拖一百次也一样。
NAV_MAX_DRAGS = 2

#: 五个标签所在的横条（OCR 用）。**比图标行低**：图标在 y=862，文字在 880–906。
NAV_LABEL_ROI = (760, 880, 1220, 906)

#: 标签行的 OCR 配方：`chi_sim`、`--psm 6`、3×（实机 2026-08-14 用的就是这一套）。
NAV_LABEL_UPSCALE = 3

#: 拖完之后导航条上的**封闭词表**。按文本定位只认这五个。
#:
#: 用户口径（2026-08-11，见 `preset_picker` 模块头）：「识别文本进行定位，
#: 而不是直接定位」。所以下面那行实测中心 x **只是量给人看的**，不进点击路径：
#:
#:     太空舱 830 · 商店 918 · 联盟 998 · 排名 1079 · 设置 1159
#:
#: 代码里点的永远是「这一屏 OCR 出来的那个 x」。写死 1079 的话，
#: 哪天条停的位置差一点，点下去就是「联盟」或「设置」。
NAV_LABELS = ("太空舱", "商店", "联盟", "排名", "设置")

#: 要找的那一个。
RANKING_LABEL = "排名"

#: 贴回 `NAV_LABELS` 时容许的编辑距离。
#:
#: 取 1 而不是更大：五个标签里四个是两字词，**两两之间的距离恰好是 2**
#: （每个字都不同）。所以 1 能容下「读错一个字」，而读错两个字时
#: `snap_to_vocabulary` 会同时贴上两个候选、判成歧义、返回 None——
#: 那正是我们要的：宁可认不出去重读/重拖，也不要把「设置」认成「排名」。
NAV_LABEL_MAX_DISTANCE = 1

#: 相邻两个词框中心相距不超过这么多像素，就当成**同一个标签被 OCR 拆开了**。
#:
#: tesseract 对中文按字切词（`preset_picker.PRESET_WORD_GAP_PX` 那条注释里
#: 有实测：`探路` 读回来是 `探` + `路`）。不合并的话，`排名` 永远只读到
#: `排` 或 `名`，贴不回词表，于是「排名」永远找不到。
#:
#: 40 的依据（从量到的五个中心推出来的）：相邻两个标签中心最近 80px
#: （排名 1079 → 设置 1159；联盟 998 → 排名 1079 是 81）。两字标签被拆开时，
#: 每个字离本标签中心约半个字宽（≈12px），于是
#:
#:     同一标签内两字相距 ≈ 24px      （盟 1010 ← 联 986）
#:     跨标签最近的两字相距 ≈ 57px    （排 1067 ← 盟 1010）
#:
#: 真正的上界是 57 而不是 80——按中心距 80 挑阈值会把「联盟」和「排名」合成
#: 一个 `联盟排名`，贴不回词表，于是「排名」永远找不到。40 落在 24 与 57 中间。
#:
#: ✅ **2026-08-14 实机量到了**（原先这是本模块唯一一个推出来的数）。
#: 拖之前那一屏的原始词框：
#:
#:     行星 839 · 舰队 920 · 太空 993 · 舱 1017 · 商店 1081 · 联盟 1161
#:
#: `太空舱` 被 tesseract 切成两个词，于是两个真实字距都拿到了：
#:
#:     同标签内   太空 993 → 舱 1017    =  24px
#:     跨标签最近 舱 1017 → 商店 1081   =  64px
#:
#: 40 落在 24 与 64 正中间，两边各有 16px 余量。合并后确实得到五个标签。
NAV_LABEL_WORD_GAP_PX = 40

# -- 排行榜面板 ----------------------------------------------------------------

#: 左上角的 ✕。与派遣面板、行星列表浮层同一处（这些浮层共用一套外框）。
RANKING_CLOSE = (750, 71)

#: ⚠️ **(1170, 70) 是「$ 充值」——禁区。** 点错就是充值页。
#:
#: 这个坐标定义在这里的**唯一理由是用来远离它**：
#: `tests/unit/game/test_ranking_ui_geometry.py` 拿它把本模块每一个会被点到的
#: 点都量一遍，离得不够远就红。所以它不是「可以点的地方」，是尺子。
#:
#: 100px 的余量远大于 `human_input.CLICK_JITTER_PX`（±4），抖动吃不掉它；
#: 当前最近的一个点是「联盟」页签(1086, 173)，距离 133px。
RECHARGE_KEEPOUT_CENTER = (1170, 70)
RECHARGE_KEEPOUT_PX = 100

#: 开面板之后等它铺开。
PANEL_OPEN_WAIT_S = 1.8

#: 「军事评分」页签。
#:
#: ⚠️ **这一步必须切对，切错拿到的是完全不同的一套数据**（实机 2026-08-14
#: 因此把一整套结论建立在错的数据上）：
#:
#:     经济评分：bot 全是 0 分、按坐标顺序排
#:     军事评分：bot 有真实分数（29.59K…）、按分数降序、坐标是乱的
#:
#: 两个页签长得一模一样，光看「切过了」证明不了切对了。
#:
#: ⚠️ **这是本模块唯一一处「按坐标点」而不是「按文本定位」的地方**，是例外，
#: 不是范例。理由：这两个页签的 OCR 试过 `--psm 7`，读得很碎（只切出三个字），
#: 做不到按文本找。例外的代价由**回读**补上——点完之后必须回读确认这一屏真的是
#: 军事榜（`ranking_nav.RankingNavigator.open_military_ranking`），
#: 判据在 `domain.ranking`。哪天有人试出能读得稳的配方，这一条就该改回按文本定位。
#:
#: 左边的「经济评分」在 (838, 212)。**故意不定义成常量**——照
#: `pirate_ui` 里「太空舱」那条的做法：定义了就迟早有人点，而点它拿到的是
#: 那套全 0 的经济数据。
MILITARY_TAB = (1084, 212)

#: 点完页签等榜单换过来。
TAB_SWITCH_WAIT_S = 1.6

#: 回读说「这还不是军事榜」时最多再点几次页签。
#:
#: 2 次而不是无限：页签点不动多半是画面根本不是排行榜面板（掉线、被浮层盖住），
#: 那时候接着点就是在认不出的画面上乱点。
MILITARY_TAB_ATTEMPTS = 2

#: 玩家 / 联盟页签 (833, 173) / (1086, 173)。**都不点**：面板打开时就在「玩家」上，
#: 而「联盟」榜是另一套数据。这里只记下位置，好让上面那把「离充值多远」的尺子量得到。
PLAYER_TAB = (833, 173)
ALLIANCE_TAB = (1086, 173)

