DRAG_STEPS = 12
DRAG_PRESS_HOLD_S = 0.15
DRAG_RELEASE_HOLD_S = 0.18

# -- 滚轮盲滚（2026-08-22 实测）------------------------------------------------
#
# `docs/军力榜翻页-滚轮实测.md` 的主结论「滚轮一次最多走约 14 像素，替代不了慢拖」
# **被推翻**。那个 14px 是真的，但它量的是**单个大 delta 事件被游戏封顶**，
# 不是滚轮的能力上限。判据是**事件形状**，不是幅度。
#
# ⚠️ 只有**盲滚段**用滚轮。检测段与采集段继续慢拖：滚轮会把列表停在**非整行位置**
# （实测偏离标定网格约 12px），而 `vision` 那边按 `ROW_FIRST_Y + k×ROW_PITCH_PX`
# 逐行裁剪——偏了就横跨两行，名字全糊。实测过一次：画面清晰，`rows_from_image`
# 只读出 2 个名次。
#
# ⚠️ **闭环盲滚要读「现在在第几名」，那一读不许走逐行裁剪**——同一颗雷。
# 2026-08-22 实机：请求 500 行，第一轮拨完当场「读不出名次」，闭环失效。
# 所以盲滚有一个**与行对齐无关**的位置读数器（`tools.ranking_scan.position_from_image`）：
# 把名次那一整列裁下来一次读完，正则抓 `[N]` 取中位数。下面
# `RANK_STRIP_*` / `SPIN_MARK_MIN_ROWS` 就是它的标定。

#: 一格滚轮的 `dwData`。**这是 Windows 的标准值，不是偏好项。**
#:
#: ⚠️ 两个方向都会**静默**失败（都是「事件发出去了、列表没走」）：
#: - **发不足一格**等于没发。`pyautogui.scroll(n)` 在 Windows 上把 `n` 原样当
#:   `dwData` 传给 `mouse_event`，**不乘 120**——`scroll(-1)` 只是 1/120 格，
#:   实测 80 次只走 0–3 行。`docs/军力榜翻页-滚轮实测.md` 里那句「1 格 = 1 像素」
#:   记的就是这个，它量的不是滚轮的幅度。
#: - **一个事件发大 delta 会被游戏封顶**：实测 100 / 400 / 800 格都只走约 14px。
#:
#: 底层鼠标钩子（`WH_MOUSE_LL`）实测：助手发 `scroll(-1)` 钩子看到 `delta=-1`，
#: 用户手动拨硬件滚轮是 `delta=-120`，而那一次走了 151 行。
WHEEL_DELTA = 120

#: 两格之间隔多久。实测用户手动连滚的间隔中位数就是 16ms，而这个数**决定成败**：
#: 游戏做的是**速度惯性**滚动，拉到 117ms/格（`pyautogui.PAUSE` 默认 0.1 秒
#: 加上事件本身的开销）就攒不起动量，80 格只走 2 行。
#:
#: ⚠️ **标定常量，不是运维旋钮。** 它量的是「多密才攒得起动量」，调了不会
#: 「更适合谁」，只会让盲滚静默地走不动。
WHEEL_GAP_S = 0.016

#: 一格推进多少行——**只是第一轮的初始猜测，不再是精度来源。**
#:
#: ⚠️⚠️ **2026-08-22 实机证伪了「拿它换算就能走准」这件事。** 两趟 × 5 组
#: （格数 40/80/160/320/480）量到的行/格：
#:
#:     格数    40     80     160    320    480
#:     第一趟  1.23   0.49   1.25   0.95   0.98
#:     第二趟  1.00   0.65   0.89   1.08   0.74
#:
#: 10 个样本：中位 **0.96**，区间 **0.49–1.25**（两端差 2.5 倍），**不随格数
#: 单调变化**——也就是说它不是一条能标定掉的系统偏差，是每一趟都会重新抽一次的
#: 噪声。按 1.08 开环换算「盲滚 700 行」，真实推进落在 **320–810 行**之间，
#: 而偏差是**静默的**：不报错、不少日志，只是采回来的数少一截。
#: （**刻意不说「拨过 `FIRST_BOT_RANK`(587)」**：用户口径 2026-08-22，那个数是
#: 玩家改名伪装出来的观测值，不是真 bot 边界，见它自己的注释。）
#:
#: ⇒ 所以 `ranking_nav.RankingNavigator.spin_blind` 改成了**闭环**（拨完读一次、
#:   不够就补拨），这个数只在**第一轮、且还没有任何本趟观测**时用一次；
#:   从第二轮起用的是本趟自己量到的行/格。它标得准不准，只影响第一轮走多远，
#:   不再影响整趟走多远。
#:
#: 每趟的实测值仍旧记进 `system_log`（`tools.ranking_scan` 的盲滚记录里那个
#: `rows_per_notch_observed`），好在事后回答「这个初始猜测还值不值得留」。
ROWS_PER_NOTCH = 1.08

#: 算格数时**除数的下界**：已知最快的那个速率。
#:
#: ⚠️ **这不是「精度标定」，是「安全边界」，两者别混。** 拿标定值去算距离已经被
#: 证伪（见上面那张表）；这里用的是另一回事——除以一个**偏大**的速率必然算出
#: **偏少**的格数，也就是让每一轮都故意走不到，剩下的交给下一轮补。精度仍然
#: 完全由测量提供，这个数只负责「不许冲过头」。
#:
#: 取 1.25：上面 10 个样本里最大的那个。`spin_blind` 用
#: `max(本趟观测..., ROWS_PER_NOTCH_MAX)` 当除数。
#:
#: ⚠️ **只取本趟观测的最大值是不够的**，这条是 2026-08-22 复审时发现的：
#: 第一轮恰好抽到区间下端（0.49）时，第二轮会按 0.49 算格数，而那一轮真实速率
#: 若跳回 1.25，就会走出 2.5 倍的距离、直接冲过头。也就是说**越是遇到慢的一轮，
#: 下一轮越危险**——而冲过头不可逆：盲滚段不读屏，榜首那一段被跳过去之后
#: 没有任何东西会发现。
#:
#: 代价是收敛慢一档：真实速率 0.49 时每轮只走掉剩余的 39%，6 轮之后仍差约 36 行。
#: **那是安全的一侧**——少走的部分由检测段接手（约 5 屏、23 秒）。
ROWS_PER_NOTCH_MAX = 1.25

#: 闭环盲滚最多补拨几轮。**标定常量，不是运维旋钮。**
#:
#: 每一轮的固定开销是「拨完等一次 `GLIDE_SETTLE_S`(2.5 秒) + 读一屏」，所以
#: 调大只是让**没收敛的那一趟**多花十几秒，调小则会让它**静默地走不到**目标
#: （走不到不报错，只是采回来的数少一截）。
#:
#: 取 6 的推导：每一轮都按「本趟观测到的最大行/格」算格数，也就是**故意走不到**、
#: 从下方逼近，于是每一轮吃掉的剩余距离最坏也有 `min/max = 0.49/1.25 ≈ 39%`。
#: 700 行按最坏比例收敛到容差 8 行以内要 `log(8/700)/log(1-0.39) ≈ 9` 轮——
#: 但那是「每一轮都恰好抽到区间两端」的连续坏运气；实测中位 0.96 时 2–3 轮就到。
#: 取 6 是在「常态两三轮足够」和「一趟最多多花 15 秒」之间取的，
#: 而没收敛也不是白跑：走过的距离照样交给检测段接手。
MAX_SPIN_ROUNDS = 6

#: 差这么多行以内就算**到位了**，不再补拨。**标定常量，不是运维旋钮。**
#:
#: ⚠️ 它和下面的 `SPIN_FINAL_APPROACH_ROWS` 各管一件事，别合成一个：
#: 这个是「到了」的判据，那个是「还差这么多就别补了」的判据。
#:
#: 取 8：位置是靠**整列一次读**出来的名次取中位数量的
#: （`tools.ranking_scan.position_from_image`），而那一读里混着自己那一行
#: （吸附的，名次和当前位置无关）和边缘上被切掉半行的读数，中位数本身就带
#: 一两行的抖动。容差比抖动还小的话，最后几轮会一直在「差 2 行」上空转，
#: 每轮白花 2.5 秒等滑行。
#:
#: 调大调小的代价高度不对称，但两边都不大：调大只是把最后几行让给检测段
#: （实测约 4.6 秒/屏，而 8 行连一屏都不到），调小只是多空转几轮。
#: **它绝不能大到能盖住一整屏**（13 行）——那样「到位了」就有可能是「整整少了一屏」。
SPIN_TOLERANCE_ROWS = 8

#: 剩余不足这么多行就**收手，不再补拨**（哪怕还没进 `SPIN_TOLERANCE_ROWS`）。
#: **标定常量，不是运维旋钮。**
#:
#: ⚠️ **这是唯一会冲过头的地方，2026-08-22 实机兑现了：请求 200 行走了 218 行。**
#: 那 18 行的超出只出在**最后一轮**：剩余只剩几行时，一格的粒度加上惯性滑行
#: 压不住，而这一轮的分母只有几格——`moved / notches` 的噪声大到离谱
#: （那一趟逐轮行/格是 0.85 / 0.98 / **2.82**，最后那个多半是测量假象而不是
#: 真速率，它还会喂进下一轮的 `rate_hi`）。
#:
#: 取 30 的理由是**代价不对称**，不是精度：最后这几十行由检测段逐屏接手，
#: 约 4 屏、18 秒，便宜；而冲过头**不可逆**——盲滚段不读内容，榜首那批 bot
#: 被跳过去之后没有任何东西会发现，采回来的数只是静悄悄少一截。
#:
#: 30 ≈ 2.3 屏（`ROWS_PER_SCROLL` 8.3），也就是「让检测段多翻两三屏」。
#: 往大调是安全方向（只是多让几屏给检测段），往小调才危险。
SPIN_FINAL_APPROACH_ROWS = 30

#: 整列读名次时，至少要抓到这么多个 `[N]`，那一次「我现在在第几名」才算数。
#: **标定常量，不是运维旋钮。**
#:
#: 取 4：中位数对两侧离群免疫，但前提是样本够多——2 个读数的「中位数」就是
#: 其中一个，而那两个都可能是串出来的高位噪声（`tools.ranking_scan.progress_mark`
#: 的注释里记着当场读到过 `[4781]`）。
#:
#: ⚠️ **不能设得更高。** 满屏 13 行里，**榜首三名是奖章图标、没有 `[N]`**，
#: 边缘那一两行还会被裁掉半个——真正抓得到的常常只有八九个，开榜那一屏更少。
#: 门槛一高，位置就「读不出来」，闭环退回开环，而开环正是这次要治的病。
#:
#: ⚠️ 不达标时**不是把这一趟判成失败**，是退回开环一次性拨完（见
#: `ranking_nav.RankingNavigator.spin_blind`）。宁可这一趟没有闭环保护，
#: 也不能让 OCR 偶发失灵把整条采集链路瘫掉。
SPIN_MARK_MIN_ROWS = 4

#: 整列读名次时，名次列左右各放宽多少像素。
#:
#: `RANK_COLUMN` 是**逐行裁剪**时量的词框边界，而整列一次读时字符会挨着边框——
#: tesseract 在 `--psm 6` 下贴边的字容易少读一个方括号，而少一个方括号就等于
#: 少一个样本（正则要求 `[N]` 成对）。左右各留 10px，代价是可能吃进一点背景，
#: 而背景里的东西不带方括号，正则本来就不收。
RANK_STRIP_PAD_PX = 10

#: 整列读名次时，**顶上**额外多留多少像素。
#:
#: 比左右宽，是因为滚轮会把列表停在非整行位置（实测偏离标定网格约 12px），
#: 首行会往上探出去一截。`ROW_FIRST_Y`(257) 减 30 = 227，仍在面板内
#: （页签在 y=212 那一行，`--psm 6` 读到它也不带方括号）。
#:
#: ⚠️ 底边刻意用 `ROW_FIRST_Y + ROWS_PER_SCREEN × ROW_PITCH_PX`（≈839）而不是
#: `RANKING_LIST_MAX_Y`(815)：多出来的那一截会把**自己那一行贴底时**的名次
#: 一起读进来，而那个名次和当前位置无关。这是有意的——中位数对一个离群值免疫，
#: 而把底边收窄会少掉一整行真样本，那对 `SPIN_MARK_MIN_ROWS` 是实打实的损失。
RANK_STRIP_TOP_PAD_PX = 30

#: 拨完之后等滑行停下来。实测惯性滑行 1.6–2.3 秒才停，取 2.5 留余量。
#:
#: ⚠️ **不等的代价是检测段在移动中的画面上读行**——逐行裁剪会横跨两行，
#: 名字全糊，而那一屏「读不出东西」和「这一屏没有 bot」在日志里长得一样。
#:
#: 这个等待**整趟只发生一次**（见 `ranking_nav.RankingNavigator.spin_blind`）。
#: 盲滚改滚轮的收益全部来自把原先 70 屏 × `SCROLL_SETTLE_WAIT_S`(2 秒) 的等待
#: 合并成这一次。
GLIDE_SETTLE_S = 2.5

#: 盲滚多少行（攻击配置页上那个框留空时的默认值）。
#:
#: 用户口径（2026-08-22）：「默认行按 700 行配置，默认值我会最终配置」。
#:
#: ⚠️ **不要拿 `FIRST_BOT_RANK`(587) 当上界去拦。** 用户口径（2026-08-22）：
#: 那个「bot 起点」是**玩家改名伪装**出来的，不是真 bot——判据只看名字前缀，
#: 改名的真人一样命中。真 bot 区在更后面，所以 700 行不越界，而
#: `BLIND_SCROLLS` 注释里「40×12=480 < 587」那套推理的前提已经不成立。
#: 拿一个被伪装污染的边界报警，比不报警更坏。
#:
#: ⚠️ **余量不是免费的，但它很便宜**：盲滚少走的距离由检测段接手，而检测段
#: 实测约 4.6 秒/屏；滚轮多走几行几乎不花钱。所以宁可多走。
BLIND_SCROLL_ROWS = 700

#: 自动标定留的余量（**行**）。守的事和 `BLIND_SCROLL_MARGIN`(10 屏) 一模一样，
#: 只是单位从屏换成了行——盲滚 = `min(最近 5 次实测行数) - 这个数`，
#: 中间少一次 `ROWS_PER_SCROLL` 换算。
#:
#: 由 `BLIND_SCROLL_MARGIN`(10 屏) × 每屏行数换算而来。⚠️ **每屏行数有两个值，
#: **算出来的，不写死**：`BLIND_SCROLL_MARGIN`(10 屏) × `ROWS_PER_SCROLL`。
#:
#: 算而不写死是为了让它不能和自己的来历分岔：日后谁把 `ROWS_PER_SCROLL` 重新标定了，
#: 这个余量会跟着走；写死一个数就会悄悄变成「10 屏」之外的另一回事。
#:
#: ⚠️ 两个每屏行数的实测值并存，取的是**大的那个**（8.3，2026-08-15，也就是本模块
#: 记着的这个）。2026-08-22 量慢拖基线得 7.3 行/拖，生产日志反推是 7.2–7.8——
#: 也就是说 8.3 偏大，于是换算出的余量偏大。**这是有意的**：余量的两侧代价完全
#: 不对称，多留一点只是多几屏廉价检测（一屏一次整列 OCR，实测 0.28 秒），
#: 少留一点则会**跳过榜首那批军力最高的 bot**，而那种漏采在页面上、日志里都看不出。
#: 所以这个数只该往大调，不该往小调。
#:
#: ⚠️ **标定常量，不是运维旋钮**，同 `BLIND_SCROLL_MARGIN`：它的下界由实测噪声
#: 的形状钉死（屏口径下噪声跨度 6 屏），调了不会「更适合谁」。可配的旋钮是
#: **盲滚行数本身**（攻击配置页上那个框，留空时用 `BLIND_SCROLL_ROWS`）。
BLIND_SCROLL_MARGIN_ROWS = round(BLIND_SCROLL_MARGIN * ROWS_PER_SCROLL)

