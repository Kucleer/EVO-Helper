#: 取 40 的算法：bot 从第 ~587 名开始；推进速率实测 8.0 名/屏，而那是今天（有游戏
#: 活动、卡顿）的数，不卡时只会更快。按一个保守的**上界** 12 名/屏 算，
#: 40 屏最多推进 480 名 < 587 —— 怎么都到不了 bot 区。
#:
#: ⚠️ **宁可少拖，不可多拖。** 少拖只是多花几次廉价检测（一屏一次整列 OCR，
#: 实测只要 0.28 秒）；多拖会**直接跳过榜首那批 bot**，而那批正是军力最高、
#: 最该先看到的。
#:
#: ✅ **2026-08-15 实机验过**：40 屏用 168 秒（4.21 秒/屏），落在名次 **~334**，
#: 离 bot 起点 587 还有 253 名的余量。实际速率 8.3 名/屏，仍远低于上界 12。
#: 往上调到 48 仍然安全（48×12=576<587），但省下的那几屏只值约 34 秒，
#: 而余量会从 253 名缩到 11 名——不划算，维持 40。
#:
#: ⚠️ **这个数现在只是「没有历史数据时的起点」**，不再是常态取值。攻击配置页
#: 那个框留空时，盲拖屏数由实测反推（见下面「盲拖屏数的自动标定」那一段）；
#: 攒不够样本才回落到这里。它守的是按名次推的那条界（40×12=480<587）——
#: 没有实测时也就只有那条界可依。
BLIND_SCROLLS = 40

#: bot 起始名次（实测 2026-08-15：盲拖 40 屏 + 检测 38 屏 = 78 屏 × 8.3 ≈ 647，
#: 与 587 相符）。只用来给 `BLIND_SCROLLS` 算余量，
#: **不作为判据**——判据是名字反解得出坐标（见 `domain.ranking.bot_rows`），
#: 真人数量会变，写死名次下次刷新就错了。
#:
#: ⚠️⚠️ **这个数不是真 bot 的起点，别拿它当安全边界。**
#: 用户口径（2026-08-22）：「bot 的起点目前是**玩家改名伪装**的 bot，并不是真正的
#: bot」。检测判据只看名字前缀（`domain.ranking.mentions_bot`），把自己改名成
#: `bot_x_y_z` 的真人一样命中——所以 587 是**被伪装污染的观测值**，真 bot 区在更后面。
#:
#: ⇒ 本模块内几处「拖过 bot 起点」的措辞（`BLIND_SCROLLS`、`BLIND_SCROLL_MARGIN`
#:   的注释）说的是**方向**，仍然成立：盲滚不该滚过 bot 区起点。但**具体这个数字
#:   不可信**，所以：不拿它拦取值、不拿它标红、不拿它算「越界了多少」。
#: ⇒ 行口径的盲滚（`BLIND_SCROLL_ROWS`）**完全不引用它**，取值由用户在攻击配置页上定。
FIRST_BOT_RANK = 587

#: 单屏实测推进多少名。2026-08-15 两次独立测量：49 屏推进 392 名 = 8.0；
#: 40 屏推进 334 名 = 8.3。取 8。
RANKS_PER_SCROLL_MEASURED = 8

#: 单屏推进的**上界**估计。只用来给 `BLIND_SCROLLS` 算余量。
#:
#: ⚠️ 必须**严格大于**实测值：那天有游戏活动、卡顿明显，不卡时只会更快。
#: 拿实测值当上界的话，余量就没了——而余量没了意味着盲拖可能拖过 bot 起点，
#: 直接跳过榜首那批军力最高的 bot。
RANKS_PER_SCROLL_MAX = 12

# -- 盲拖屏数的自动标定 --------------------------------------------------------
#
# `BLIND_SCROLLS` 只是**没有历史数据时**的起点。攻击配置页上那个框留空时，
# 盲拖屏数由每趟采集自己量出来的「翻了 N 屏到达 bot 区」反推
# （`domain.ranking.calibrated_blind_scrolls`）；填了数就锁死，不再自动调。
#
# 生产实测（2026-08-17 同一天六趟）：77 / 78 / 73 / 74 / 72 / 78。

#: 自动标定取最近几次实测。
#:
#: 取 5：**不能取最近一次**——上面六次的跨度是 6 屏（72–78），拿其中偏大的
#: 那一次去设盲拖就会拖过 bot 起点。也不能取太小的窗口：`77 / 78 / 78` 这样
#: 连着三次偏大的窗口在实测里真的出现过，K=3 的最小值就是 77。
#: 实机每天约 8 趟，5 次不到一天就攒齐。
#:
#: ⚠️ **这不是偏好项，是标定常量**（2026-08-17 审计）。可配的旋钮是**盲拖屏数
#: 本身**（攻击配置页那个框），而这两个数是那条标定公式的参数：取值由实测噪声的
#: 形状决定，调了不会「更适合谁」，只会让标定算出一个错的屏数。
BLIND_SCROLL_SAMPLES = 5

#: 自动标定留的余量（屏）。盲拖 = `min(最近 5 次实测) - 10`。
#:
#: ⚠️ **不能小于实测噪声跨度 6**（72–78），否则算出来的盲拖会落进噪声区间里，
#: 也就是「某些趟必然拖过头」。取 10 而不是刚好 6：只有六个样本、还都来自同一天，
#: 观测到的跨度必然低估真实的散布，多留 4 屏当缓冲。
#:
#: 代价是完全不对称的，所以宁可留厚：多留一屏余量只是多一次整列 OCR
#: （实测 0.28 秒），少留一屏则可能**跳过榜首那批军力最高的 bot**，
#: 而采回来的数只是静悄悄少一截，页面上、日志里都看不出异常。
#:
#: ⚠️ **这不是偏好项，是标定常量**，同 `BLIND_SCROLL_SAMPLES`：它的下界由实测
#: 噪声跨度（6 屏）钉死，调到 6 以下就等于「某些趟必然拖过头」。
BLIND_SCROLL_MARGIN = 10

#: 用户能在攻击配置页上**手填**的盲拖屏数上界（当前取值 62）。
#:
#: 就是把自动标定那道公式套在已记录的实测上：`min(72) - 10 = 62`。这样用户想把
#: 当下自动算出来的值钉死时填得进去，而手填的数又不会越过**有实测支撑**的那条线。
#:
#: ⚠️ **它比按名次推的那条界（48）宽，这是有意的。** 那条界走的是
#: 「`RANKS_PER_SCROLL_MAX`(12) 名/屏 × 屏数 < `FIRST_BOT_RANK`(587)」，
#: 而 12 是一个**从没观测到过**的悲观上界（三天实测都是 8.0–8.3）。屏数是直接
#: 量到的量，中间不经过那次换算，证据强得多。`BLIND_SCROLLS` 那个默认值仍然
#: 守着按名次推的那条界——没有历史数据时也就只有那条界可依。
#:
#: ⚠️ **必须有这条上界。** 这个值调大的代价不对称：调小只是多花几屏廉价检测，
#: 调大则会**盲拖越过 bot 起点**，把榜首那批军力最高的 bot 整段跳过去，
#: 而页面上看不出任何异常。宁小勿大——越界当场拒掉，不照单收下。
BLIND_SCROLLS_MAX = 62

#: 盲拖之后**留给「到 bot 区了没有」检测的屏数预算**。
#:
#: 真人段整体要翻的屏数 = `盲拖屏数 + 这个预算`。写成加法是有原因的：原先它是
#: `tools.ranking_scan.scan()` 上一个裸的默认形参 `human_scrolls = 140`，判据写作
#: `scrolled >= human_scrolls`，而 `scrolled` 从 `blind_scrolls` 起步——于是
#: **盲拖调大，检测预算等量缩小**，耦合是隐式且反向的，没有一行注释、没有一条测试。
#: 盲拖屏数是会自动标定的（见上面那一段），也就是说那个预算会在没人察觉的情况下
#: 一天天变小，直到某天不够用。改成加法之后，两个数各说各的事。
#:
#: 取 60 的推导：
#:
#:     实测真人段跨度            72 – 82 屏（13 个样本，最近三次都是 79）
#:     最坏情况下还要检测多少     82 − `BLIND_SCROLLS_MAX`(62) = 20 屏
#:     给 3 倍余量               20 × 3 = 60
#:
#: 今天的等价取值是 70 + 60 = 130，与原先写死的 140 基本一致——**这是把形状摆正，
#: 不是调大**。
#:
#: ⚠️ **这不是偏好项，是标定常量。** 取值由榜单长度与滚动速率决定，调了不会让结果
#: 「更适合谁」，只会让它变错：调小会在真人段还没翻完时收工（把一整趟扔掉），
#: 调大只是让一趟坏掉的采集多空转几分钟。真人段真的变长了，该由已有的自动标定接住
#: （`bot_area_scrolls` 的样本就在库里），不该让用户手填。
#:
#: 检测一屏的代价：一次整列 OCR，实测 0.28 秒 + 一次滚动约 4.2 秒。
BOT_DETECTION_BUDGET_SCROLLS = 60

#: 翻真人段时每隔这么多屏留一次现场（名字列摘要 + 与上一次的重合率）。
#:
#: ⚠️ **不留现场的代价 2026-08-18 兑现了**：那一轮「采不到」里，「列表根本没动」
#: 「开错了面板」「bot 名字读不出来」三种可能**完全不可分辨**——而仓库口径是
#: 「出事时能不能只靠库里的日志定位」。
#:
#: 10 屏 ≈ 50 秒一条，一趟 130 屏最多 13 条，进库不算刷屏；比这更密就是在
#: 往 `system_log` 里灌流水账（每 tick 可能触发的必须限流，见 CLAUDE.md）。
NAME_SAMPLE_EVERY_SCROLLS = 10

#: 每条现场里名字列摘要留多少字符。够认出「这一屏和上一屏不是同一批人」就行。
NAME_SAMPLE_CHARS = 60

#: 连着几次抽样的重合率高过这个值，就说明**列表压根没在动**。
#:
#: 正常滚动一屏推进约 8 名、一屏 13 行，所以隔 10 屏的两次抽样几乎不该有重合。
#: 取 0.8 是留足余量：它要认的是「几乎一模一样」，不是「有点像」。
NAME_SAMPLE_STUCK_OVERLAP = 0.8

#: 采集段里连续几屏一个新 bot 都没有，才算这一段到头了。
#:
#: ⚠️ **不能复用 `SCROLL_STALL_CONFIRMATIONS`(3)。** 2026-08-15 实机用它当判据，
#: 刚翻到 bot 区就当场触发——边界那几屏大半还是真人，本来就没几个新 bot，
#: 于是一趟只写了 2 条，而 bot 段有四千多个。
#:
#: 取 12：bot 段里每屏期望约 8 个新的（实测），连着 12 屏一个都没有，
#: 才是「真的到头了」而不是「正好走在稀疏的一段上」。
DRY_SCREENS = 12

#: 连续几次「最大名次没往前走」才算滚到底了。
#:
#: ⚠️ **不能只看「两屏 OCR 输出完全相等」**（`ranking_nav.scroll_once` 那条）。
#: 那条是**充分**判据（逐字节相同当然没动），但实机上几乎永远不成立：中文玩家名
#: 在 `eng` 下读成噪声，同一行连读两次就是两个不同的字符串。于是它一次都不会触发，
#: 循环只能靠次数上限收工——而那时你不知道是读完了还是拖不动了。
#:
#: 取 3 而不是 1：今天（2026-08-15，游戏活动）卡顿明显，单次拖动没生效是常态。
#: 1 次就判到底，会把半截榜单当成完整榜单收工，而且日志上看着一切正常。
SCROLL_STALL_CONFIRMATIONS = 3

